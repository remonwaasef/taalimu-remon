function arrayToCode($array, $indent = 1)
{
    if (empty($array)) {
        return '[]';
    }
    $code = "[\n";
    $spaces = str_repeat('    ', $indent);
    foreach ($array as $key => $value) {
        $code .= $spaces."'".addslashes($key)."' => '".addslashes($value)."',\n";
    }
    $code .= str_repeat('    ', $indent - 1).']';

    return $code;
}

